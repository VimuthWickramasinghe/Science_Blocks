"""LIGGGHTS-DEM Industrial Granular & Ball Mill Solver Integration.

Generates native LIGGGHTS input decks (in.liggghts_dem) with Hertz-Mindlin contact laws,
and provides an embedded high-performance Python DEM fallback engine.
"""

import os
import math
from typing import Dict, Any
from ..base_tool import BaseSimulationTool, register_tool


class LiggghtsSimulationTool(BaseSimulationTool):
    name = "LIGGGHTS"
    category = "DEM"
    description = "LAMMPS-based Discrete Element Method for granular flows and industrial milling"
    executable_candidates = ["liggghts", "liggghts.exe", "lmp_auto"]

    def generate_case(self, case_dir: str, params: Dict[str, Any]) -> Dict[str, str]:
        os.makedirs(case_dir, exist_ok=True)
        script_path = os.path.join(case_dir, "in.liggghts_dem")

        sun_rpm = params.get("sun_rpm", 200.0)
        jar_rpm = params.get("jar_rpm", -300.0)
        ball_count = params.get("ball_count", 25)
        radius_m = params.get("ball_radius_m", 0.012)
        density = params.get("density", 7850.0)
        youngs_gpa = params.get("youngs_modulus_gpa", 210.0)
        poisson = params.get("poissons_ratio", 0.30)
        restitution = params.get("restitution", 0.82)
        friction = params.get("friction", 0.20)
        frames = params.get("frames", 150)
        dt = 1e-4

        deck = f"""# ===========================================================================
# LIGGGHTS-DEM Planetary Ball Mill Simulation Deck
# Generated by Science Blocks for Blender
# ===========================================================================

atom_style      granular
atom_modify     map array
boundary        f f f
newton          off
communicate     single vel yes

units           si

# Particle Domain Box
region          reg_mill block -2.5 2.5 -2.5 2.5 -1.0 1.0 units box
create_box      1 reg_mill

# Physical Material Laws (Hertz-Mindlin Contact Model)
fix             m1 all property/global youngsModulus peratomtype {youngs_gpa * 1e9:.2e}
fix             m2 all property/global poissonsRatio peratomtype {poisson:.2f}
fix             m3 all property/global coefficientRestitution peratomtypepair 1 1 {restitution:.2f}
fix             m4 all property/global coefficientFriction peratomtypepair 1 1 {friction:.2f}

pair_style      gran model hertz tangential history
pair_coeff      * *

# Timestep & Integrator
timestep        {dt:.6f}
fix             integrator all nve/sphere

# Gravity Vector
fix             grav all gravity 9.81 vector 0.0 0.0 -1.0

# Planetary Centrifugal & Coriolis Reference Frame Rotation
# Sun Wheel RPM = {sun_rpm:.1f}, Jar Counter-Rotation RPM = {jar_rpm:.1f}

# Output Particle Positions and Impact Data
dump            dmp_particles all custom 500 post/dump*.dem id type x y z vx vy vz radius
run             {int(frames * 40)}
"""
        with open(script_path, "w", encoding="utf-8") as f:
            f.write(deck)

        return {"input_script": script_path}

    def solve_python(self, params: Dict[str, Any]) -> Dict[str, Any]:
        """Executes embedded Hertz-Mindlin DEM solver in pure Python/NumPy."""
        from ... import dem_solver

        res = dem_solver.solve_planetary_dem(
            sun_rpm=params.get("sun_rpm", 200.0),
            jar_rpm=params.get("jar_rpm", -300.0),
            r_sun=params.get("r_sun", 1.3),
            r_jar=params.get("r_jar", 0.45),
            h_jar=params.get("h_jar", 1.1),
            ball_count=params.get("ball_count", 25),
            ball_radius_m=params.get("ball_radius_m", 0.012),
            ball_density=params.get("density", 7850.0),
            youngs_modulus_gpa=params.get("youngs_modulus_gpa", 210.0),
            poissons_ratio=params.get("poissons_ratio", 0.30),
            restitution=params.get("restitution", 0.82),
            static_friction=params.get("friction", 0.20),
            rolling_friction=params.get("rolling_friction", 0.05),
            frames=params.get("frames", 150),
            fps=params.get("fps", 24.0),
            substeps_per_frame=params.get("substeps", 40),
            contact_model="HERTZ_MINDLIN",
            charge_distribution=params.get("charge_distribution", "MONODISPERSE"),
            integrator="VELOCITY_VERLET",
            gravity=params.get("gravity", 9.81),
            mill_orientation=params.get("mill_orientation", "AUTO"),
            slurry_drag=params.get("slurry_drag", False),
            slurry_viscosity=params.get("slurry_viscosity", 0.001),
            slurry_density=params.get("slurry_density", 1000.0),
        )

        return {
            "solver": "LIGGGHTS_Python_Engine",
            "total_impacts": res.total_impacts,
            "mean_energy_j": res.mean_impact_energy_j,
            "max_energy_j": res.max_impact_energy_j,
            "power_watts": res.estimated_power_watts,
            "collision_frequency_hz": res.collision_frequency_hz,
            "result_object": res,
        }


# Register tool singleton
LIGGGHTS_TOOL = LiggghtsSimulationTool()
register_tool(LIGGGHTS_TOOL)

