"""Elmer Multiphysics Thermal-Mechanical Dissipation Integration.

Generates native Elmer Solver Input Files (.sif) and provides an embedded
thermodynamic heat generation and dissipation solver in pure Python/NumPy.
"""

import os
import math
from typing import Dict, Any
from ..base_tool import BaseSimulationTool, register_tool


class ElmerSimulationTool(BaseSimulationTool):
    name = "Elmer"
    category = "MULTIPHYSICS"
    description = "Elmer multi-physics finite element suite for thermal dissipation and heat transfer"
    executable_candidates = ["ElmerSolver", "ElmerSolver.exe", "elmersolver"]

    def generate_case(self, case_dir: str, params: Dict[str, Any]) -> Dict[str, str]:
        os.makedirs(case_dir, exist_ok=True)
        sif_path = os.path.join(case_dir, "case.sif")

        power_watts = params.get("power_watts", 500.0)
        ambient_temp = params.get("ambient_temp_c", 20.0)

        sif = f"""! ===========================================================================
! Elmer Multiphysics Simulation Input File
! Generated by Science Blocks for Planetary Mill Heat Dissipation
! ===========================================================================
Header
  CHECK KEYWORDS Warn
  Mesh DB "." "mesh"
  Include Path ""
  Results Directory "results"
End

Simulation
  Max Output Level = 5
  Coordinate System = Cartesian
  Coordinate Mapping(3) = 1 2 3
  Simulation Type = Transient
  Steady State Max Iterations = 1
  Timestep intervals = 100
  Timestep Sizes = 0.5
End

Body 1
  Target Bodies(1) = 1
  Equation = 1
  Material = 1
  Body Force = 1
  Initial Condition = 1
End

Material 1
  Name = "Steel Jar Wall"
  Density = 7850.0
  Heat Capacity = 480.0
  Heat Conductivity = 45.0
End

Body Force 1
  Heat Source = {power_watts:.2f}
End

Equation 1
  Active Solvers(1) = 1
End

Solver 1
  Equation = Heat Equation
  Procedure = "HeatSolve" "HeatSolver"
  Variable = Temperature
  Exec Solver = Always
  Stabilize = True
  Linear System Solver = Iterative
  Linear System Iterative Method = BiCGStab
  Linear System Max Iterations = 500
  Linear System Convergence Tolerance = 1.0e-8
End
"""
        with open(sif_path, "w", encoding="utf-8") as f:
            f.write(sif)
        return {"sif_file": sif_path}

    def solve_python(self, params: Dict[str, Any]) -> Dict[str, Any]:
        """Calculates transient thermal dissipation and jar temperature rise."""
        power_watts = params.get("power_watts", 500.0)  # Milling mechanical power
        thermal_efficiency = params.get("heat_fraction", 0.85)  # 85% converted to heat
        jar_mass_kg = params.get("jar_mass_kg", 8.5)
        charge_mass_kg = params.get("charge_mass_kg", 1.5)
        total_thermal_mass = (jar_mass_kg * 480.0) + (charge_mass_kg * 480.0)  # J/K
        ambient_temp_c = params.get("ambient_temp_c", 20.0)
        milling_duration_min = params.get("milling_duration_min", 30.0)
        cooling_type = params.get("cooling_type", "AIR_CONVECTION")

        # Convective heat transfer coefficient h (W/m^2 K)
        # Air natural/forced convection: h ~ 15 - 45 W/m^2 K. Water cooling: h ~ 300 W/m^2 K
        h_conv = 35.0 if cooling_type == "AIR_CONVECTION" else 350.0
        r_jar = params.get("r_jar", 0.45)
        h_jar = params.get("h_jar", 1.1)
        surface_area = 2.0 * math.pi * r_jar * h_jar + 2.0 * math.pi * (r_jar**2)

        heat_gen_watts = power_watts * thermal_efficiency
        # Steady-state temperature rise: Delta T_ss = q_dot / (h * A)
        delta_t_ss = heat_gen_watts / max(1.0, (h_conv * surface_area))
        t_ss = ambient_temp_c + delta_t_ss

        # Thermal time constant: tau = C_thermal / (h * A)
        tau_seconds = total_thermal_mass / max(1.0, (h_conv * surface_area))

        # Transient temperature after duration
        t_seconds = milling_duration_min * 60.0
        delta_t_transient = delta_t_ss * (1.0 - math.exp(-t_seconds / max(1.0, tau_seconds)))
        t_final = ambient_temp_c + delta_t_transient

        return {
            "solver": "Elmer_Python_Thermal_Engine",
            "heat_generation_rate_w": float(heat_gen_watts),
            "final_temperature_c": float(t_final),
            "temperature_rise_delta_c": float(delta_t_transient),
            "steady_state_temp_c": float(t_ss),
            "thermal_time_constant_min": float(tau_seconds / 60.0),
            "thermal_status": "Normal Operating Range" if t_final < 75.0 else ("Elevated Warm" if t_final < 120.0 else "Critical Overheating Warning"),
        }


ELMER_TOOL = ElmerSimulationTool()
register_tool(ELMER_TOOL)

